//! Emits `src/wasm.rs` of the interface crate: for each extension point trait,
//! `Foreign<Trait>`, which wraps a JS object as the trait for the core, and
//! `Wasm<Trait>`, the wasm-bindgen class that exports a Rust provider to JS.
//!
//! Both speak the raw interface [`crate::ts::adapters`] declares. The generic
//! helpers they call live in the hand-written `src/wasm/support.rs`.

use std::{collections::BTreeSet, fmt::Write};

use indoc::formatdoc;

use crate::model::{ExtensionTrait, Extensions, Method, MethodKind, TypeRef, camel_case};

/// `src/wasm.rs`.
pub fn wasm_bridge(extensions: &Extensions) -> String {
	let has_streams = extensions.traits.iter().any(|extension| {
		extension
			.methods
			.iter()
			.any(|method| matches!(method.kind, MethodKind::Stream { .. }))
	});
	let mut crate_imports = BTreeSet::new();
	let mut foreign = String::new();
	let mut exported = String::new();
	for extension in &extensions.traits {
		foreign.push_str(&foreign_wrapper(extension, &mut crate_imports));
		exported.push_str(&export_wrapper(extension));
	}

	let names = |items: Vec<String>| items.join(", ");
	let reexports = names(
		extensions
			.traits
			.iter()
			.map(|extension| format!("Wasm{}", extension.name))
			.collect(),
	);
	let crate_imports = names(crate_imports.into_iter().collect());
	let stream_import = if has_streams { "use futures::stream::BoxStream;\n" } else { "" };
	let export_imports = export_imports(extensions);

	formatdoc!(
		r#"
		//! Generated by sketch-codegen from the `{crate_name}` crate. Do not edit.
		//!
		//! The web side of each extension point. `Foreign<Trait>` wraps a JS object
		//! implementing the trait's raw interface as the trait, for the core.
		//! `Wasm<Trait>`, behind the `export` feature, exports a Rust implementation
		//! to JS with that same interface. Values cross as SCALE bytes; `support`
		//! holds the conversions.

		mod support;

		{stream_import}use wasm_bindgen::JsValue;

		#[cfg(feature = "export")]
		pub use self::export::{{{reexports}}};
		use self::support::JsMethod;
		use crate::{{{crate_imports}}};
		{foreign}
		#[cfg(feature = "export")]
		mod export {{
		{export_imports}
		{exported}}}
		"#,
		crate_name = extensions.crate_name,
	)
}

fn foreign_wrapper(extension: &ExtensionTrait, crate_imports: &mut BTreeSet<String>) -> String {
	let name = &extension.name;
	crate_imports.insert(name.clone());
	let mut fields = String::new();
	let mut lookups = String::new();
	let mut methods = Vec::new();
	for method in &extension.methods {
		let field = &method.name;
		let js_name = camel_case(field);
		writeln!(fields, "\t{field}: JsMethod,").expect("writing to a String cannot fail");
		writeln!(lookups, "\t\t\t{field}: JsMethod::lookup(object, \"{js_name}\")?,")
			.expect("writing to a String cannot fail");

		let params: String = method
			.params
			.iter()
			.map(|param| format!(", {}: {}", param.name, rust_type(&param.type_ref, crate_imports)))
			.collect();
		let args = method
			.params
			.iter()
			.map(|param| format!("support::encode(&{})", param.name))
			.collect::<Vec<_>>()
			.join(", ");
		let error = method.error();
		crate_imports.insert(error.to_string());
		methods.push(match &method.kind {
			MethodKind::Async { ok, .. } => formatdoc!(
				"
					async fn {field}(&self{params}) -> Result<{ok}, {error}> {{
						self.{field}.call(vec![{args}]).await
					}}",
				ok = rust_type(ok, crate_imports),
			),
			MethodKind::Stream { item, .. } => formatdoc!(
				"
					fn {field}(&self{params}) -> BoxStream<'static, Result<{item}, {error}>> {{
						self.{field}.subscribe(vec![{args}])
					}}",
				item = rust_type(item, crate_imports),
			),
		});
	}
	let methods = methods.join("\n\n");

	formatdoc!(
		"

		/// A JS object implementing the raw `{name}` interface, as a [`{name}`] for the
		/// core.
		pub struct Foreign{name} {{
		{fields}}}

		impl Foreign{name} {{
			/// Wraps `object`, failing when one of the interface's methods is missing.
			pub fn new(object: &JsValue) -> Result<Self, JsValue> {{
				Ok(Self {{
		{lookups}		}})
			}}
		}}

		#[async_trait::async_trait]
		impl {name} for Foreign{name} {{
			{methods}
		}}
		"
	)
}

fn export_imports(extensions: &Extensions) -> String {
	let methods = || extensions.traits.iter().flat_map(|extension| &extension.methods);
	let mut js_types = Vec::new();
	if methods().any(|method| matches!(method.kind, MethodKind::Stream { .. })) {
		js_types.push("Function");
	}
	if methods().any(|method| matches!(method.kind, MethodKind::Async { .. })) {
		js_types.push("Promise");
	}
	if methods().any(|method| !method.params.is_empty()) {
		js_types.push("Uint8Array");
	}
	let mut crate_names: BTreeSet<&str> =
		extensions.traits.iter().map(|extension| extension.name.as_str()).collect();
	crate_names.extend(methods().filter(|method| !method.params.is_empty()).map(Method::error));

	formatdoc!(
		"
			use std::sync::Arc;

			use js_sys::{{{js_types}}};
			use wasm_bindgen::prelude::wasm_bindgen;

			use super::support;
			use crate::{{{crate_names}}};
		",
		js_types = js_types.join(", "),
		crate_names = crate_names.into_iter().collect::<Vec<_>>().join(", "),
	)
}

fn export_wrapper(extension: &ExtensionTrait) -> String {
	let name = &extension.name;
	let mut methods = Vec::new();
	for method in &extension.methods {
		let rust_name = &method.name;
		let js_name = camel_case(rust_name);
		let js_name_attr =
			if &js_name == rust_name { String::new() } else { format!("js_name = {js_name}, ") };
		let error = method.error();
		let raw_params: String = method
			.params
			.iter()
			.map(|param| format!(", {}: Uint8Array", param.name))
			.collect();
		let decoded_args = method
			.params
			.iter()
			.map(|param| format!("support::decode::<_, {error}>(&{})?", param.name))
			.collect::<Vec<_>>()
			.join(", ");
		let docs = rust_docs(method.docs.as_deref());
		methods.push(match &method.kind {
			MethodKind::Async { .. } => formatdoc!(
				r#"
				{docs}#[wasm_bindgen({js_name_attr}unchecked_return_type = "Promise<Uint8Array>")]
				pub fn {rust_name}(&self{raw_params}) -> Promise {{
					let inner = Arc::clone(&self.inner);
					support::export_async(async move {{ inner.{rust_name}({decoded_args}).await }})
				}}"#
			),
			MethodKind::Stream { .. } => formatdoc!(
				r#"
				{docs}#[wasm_bindgen({js_name_attr}unchecked_return_type = "() => void")]
				pub fn {rust_name}(
					&self{raw_params},
					#[wasm_bindgen(unchecked_param_type = "(item: Uint8Array) => void")] on_item: Function,
					#[wasm_bindgen(unchecked_param_type = "(error: unknown) => void")] on_error: Function,
				) -> Function {{
					support::export_stream(|| Ok(self.inner.{rust_name}({decoded_args})), on_item, on_error)
				}}"#
			),
		});
	}
	let methods = methods.join("\n\n");

	formatdoc!(
		"

			/// A Rust [`{name}`] exported to JS with the raw `{name}` interface, for web
			/// host code to pass to the core or wrap.
			#[wasm_bindgen]
			pub struct Wasm{name} {{
				inner: Arc<dyn {name}>,
			}}

			impl Wasm{name} {{
				/// Exports `inner` to JS.
				pub fn new(inner: Arc<dyn {name}>) -> Self {{
					Self {{ inner }}
				}}
			}}

			#[wasm_bindgen]
			impl Wasm{name} {{
				{methods}
			}}
		"
	)
}

/// Rust spelling of a type, recording the crate types it names.
fn rust_type(type_ref: &TypeRef, crate_imports: &mut BTreeSet<String>) -> String {
	match type_ref {
		TypeRef::Unit => "()".into(),
		TypeRef::Bool => "bool".into(),
		TypeRef::U8 => "u8".into(),
		TypeRef::U16 => "u16".into(),
		TypeRef::U32 => "u32".into(),
		TypeRef::U64 => "u64".into(),
		TypeRef::String => "String".into(),
		TypeRef::Bytes => "Vec<u8>".into(),
		TypeRef::FixedBytes(len) => format!("[u8; {len}]"),
		TypeRef::Vec(element) => format!("Vec<{}>", rust_type(element, crate_imports)),
		TypeRef::Option(inner) => format!("Option<{}>", rust_type(inner, crate_imports)),
		TypeRef::Named(name) => {
			crate_imports.insert(name.clone());
			name.clone()
		},
	}
}

/// `///` lines for `docs`; empty without docs.
fn rust_docs(docs: Option<&str>) -> String {
	docs.map(str::trim)
		.filter(|docs| !docs.is_empty())
		.map(|docs| {
			docs.lines()
				.map(
					|line| {
						if line.is_empty() { "///\n".to_string() } else { format!("/// {line}\n") }
					},
				)
				.collect()
		})
		.unwrap_or_default()
}
